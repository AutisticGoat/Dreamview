# Crea la migracion base 0_init para PostgreSQL y la marca como aplicada
# en una base que ya tiene las tablas (creadas antes con db push).
#
# Uso, desde la raiz del repositorio (URL entre comillas simples):
#   powershell -ExecutionPolicy Bypass -File .\scripts\db\crear-migracion-base.ps1 -DatabaseUrl 'postgres://...'
#
# Correlo solo contra produccion (defaultdb). La base de staging nueva
# no lo necesita: el pipeline le aplicara 0_init con migrate deploy.

param([Parameter(Mandatory = $true)][string]$DatabaseUrl)

$ErrorActionPreference = 'Stop'
Set-Location (Resolve-Path "$PSScriptRoot\..\..")

$mig      = 'prisma\migrations'
$lockPath = Join-Path (Get-Location) "$mig\migration_lock.toml"
$respaldo = '..\respaldo-migraciones-mysql'
$env:DATABASE_URL = $DatabaseUrl

try {
  # 1. Sacar del repositorio las migraciones viejas de MySQL
  if ((Test-Path $lockPath) -and ((Get-Content $lockPath -Raw) -match 'mysql')) {
    New-Item -ItemType Directory -Force $respaldo | Out-Null
    Get-ChildItem $mig | Move-Item -Destination $respaldo -Force
    Write-Host "Migraciones MySQL movidas a $respaldo" -ForegroundColor Yellow
  }

  # 2. Generar 0_init desde el schema
  if (-not (Test-Path "$mig\0_init\migration.sql")) {
    New-Item -ItemType Directory -Force "$mig\0_init" | Out-Null
    npx prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script --output "$mig/0_init/migration.sql"
    if ($LASTEXITCODE -ne 0) { throw 'No se pudo generar 0_init' }
    $lock = "# Please do not edit this file manually`n# It should be added in your version-control system (e.g., Git)`nprovider = `"postgresql`"`n"
    [System.IO.File]::WriteAllText($lockPath, $lock, (New-Object System.Text.UTF8Encoding $false))
    Write-Host 'Migracion 0_init creada' -ForegroundColor Green
  }

  # 3. Comprobar que la base coincide con el schema antes de marcarla
  npx prisma migrate diff --from-url $DatabaseUrl --to-schema-datamodel prisma/schema.prisma --exit-code
  if ($LASTEXITCODE -eq 2) { throw 'La base y el schema NO coinciden. No se marco nada. Pega este log en el chat.' }
  if ($LASTEXITCODE -ne 0) { throw 'No se pudo comparar la base con el schema' }

  # 4. Marcar 0_init como aplicada y mostrar el estado
  npx prisma migrate resolve --applied 0_init
  npx prisma migrate status
  Write-Host 'Listo: 0_init marcada como aplicada' -ForegroundColor Green
}
finally {
  Remove-Item Env:DATABASE_URL -ErrorAction SilentlyContinue
}
